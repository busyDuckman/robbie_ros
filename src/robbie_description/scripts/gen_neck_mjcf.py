#!/usr/bin/env python3
"""Builds the neck's MuJoCo model (MJCF) from config/neck.yaml.

Usage: gen_neck_mjcf.py neck.yaml CW|CCW out.xml

Run by the CMake build, once per pole: CW or CCW twist, seen from above. The pole isn't in
neck.yaml because the owner can turn the neck into either one by hand. The model is written in
its rest pose (that pole, sleds at start_deg), so every joint's zero is that pose and the closed
loop starts satisfied.

The head faces head.rotation_deg on the platform: 0 is from the platform centre to rod end 1,
CCW seen from above (docs/head_rotation.svg). The head site, and so the sim's head pose, is in
that frame.

The neck, as modelled:
  - Each sled is a hinge about the collar axis, driven by a position actuator.
  - Each rod has a rod end at both ends, on a radial screw. A rod end swings freely about its
    screw, and its swivel is limited on the twist side. Those limits, top and bottom, are what
    hold the pole.
  - The rod's top rod end is welded to the free-floating platform, which closes the loop.
  - The springs are tendons between neighbouring rods' spring mounts. They only pull, like the
    real extension springs.
"""

import math
import sys

import yaml


def v_add(a, b):
    return [x + y for x, y in zip(a, b)]


def v_sub(a, b):
    return [x - y for x, y in zip(a, b)]


def v_scale(a, s):
    return [x * s for x in a]


def v_norm(a):
    return math.sqrt(sum(x * x for x in a))


def v_unit(a):
    return v_scale(a, 1.0 / v_norm(a))


def v_cross(a, b):
    return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]


def fmt(v):
    return " ".join(f"{x:.6g}" for x in v)


def orbit_dir(deg):
    """Unit vector from the collar centre to a sled at orbit angle deg (0 is -Y, as in openscad)."""
    a = math.radians(deg)
    return [math.sin(a), -math.cos(a), 0.0]


def build(cfg, pole):
    if pole not in ("CW", "CCW"):
        raise ValueError(f"pole must be CW or CCW, not {pole!r}")
    g = cfg["gears"]
    sled, rod, plat = cfg["sled"], cfg["rod"], cfg["platform"]
    springs, rod_end = cfg["springs"], cfg["rod_end"]

    pinion_dist = g["module"] * (g["ring_teeth"] - g["pinion_teeth"]) / 2
    z_pivot = cfg["collar_z"] + sled["pivot_height"]
    # The twist at rest follows from the rod length, the two pivot radii and the rest height.
    rb, rp, height = sled["pivot_radius"], plat["pivot_radius"], plat["rest_height"]
    chord_sq = rod["length"] ** 2 - height ** 2
    cos_twist = (rb ** 2 + rp ** 2 - chord_sq) / (2 * rb * rp)
    if chord_sq <= 0 or abs(cos_twist) > 1:
        sys.exit("neck.yaml: rod.length, the pivot radii and platform.rest_height don't fit together")
    twist = math.copysign(math.degrees(math.acos(cos_twist)), 1 if pole == "CCW" else -1)
    z_top = z_pivot + height
    # Head frame zero: the world angle of rod end 1 at rest (orbit_dir's 0 is -Y).
    zero = sled["start_deg"][0] + twist - 90
    facing = math.radians(zero + cfg["head"]["rotation_deg"])

    # Rod ends in the rest pose: bottom on the sled, top on the platform, twisted round by twist.
    bottoms, tops = [], []
    for deg in sled["start_deg"]:
        bottoms.append(v_add(v_scale(orbit_dir(deg), rb), [0, 0, z_pivot]))
        tops.append(v_add(v_scale(orbit_dir(deg + twist), rp), [0, 0, z_top]))

    # Spring mounts, from_top along each rod from its top pivot.
    f = springs["from_top"] / rod["length"]
    mounts = [v_add(t, v_scale(v_sub(b, t), f)) for b, t in zip(bottoms, tops)]
    spring_len = [v_norm(v_sub(mounts[i], mounts[(i + 1) % 3])) for i in range(3)]

    x = []
    x.append('<mujoco model="robbie_neck">')
    x.append("  <!-- Generated by robbie_description/scripts/gen_neck_mjcf.py from config/neck.yaml. Don't edit. -->")
    x.append(f"  <!-- Rest pose: platform {height * 1000:.1f} mm above the sled pivots, twist {twist:.1f} deg,"
             f" springs {spring_len[0] * 1000:.1f} mm between mounts. -->")
    x.append('  <compiler angle="radian" autolimits="true"/>')
    x.append('  <option timestep="0.001" integrator="implicitfast"/>')
    x.append("  <default>")
    x.append('    <geom contype="0" conaffinity="0" rgba="0.15 0.15 0.15 1"/>')
    x.append('    <default class="sled_collide"><geom contype="2" conaffinity="2"/></default>')
    # Rod-end joints. MuJoCo scales limit stiffness by the joint's effective inertia, and rod ends
    # weigh next to nothing, so armature stands in for it. Without it the limits can't hold the
    # platform up; much less and it hops between solutions.
    x.append('    <default class="rod_end"><joint type="hinge" armature="1e-3" damping="1e-4"/></default>')
    x.append("  </default>")
    # For looks: a hexagonal platform with a rod end just outside the middle of every second edge
    # (docs/head_rotation.svg). Edge middles sit hex_inset inside the rod-end centres.
    hex_inset = 0.006
    corner = (rp - hex_inset) / math.cos(math.radians(30))
    verts = [fmt([corner * math.cos(math.radians(zero + 30 + 60 * k)), corner * math.sin(math.radians(zero + 30 + 60 * k)), z])
             for z in (-0.004, 0.004) for k in range(6)]
    x.append("  <asset>")
    x.append(f'    <mesh name="platform" vertex="{" ".join(verts)}"/>')
    x.append("  </asset>")
    x.append("  <worldbody>")
    # The base and the collar, for looks.
    x.append(f'    <geom name="base" type="cylinder" size="0.075 {cfg["collar_z"] / 2:.6g}"'
             f' pos="0 0 {cfg["collar_z"] / 2:.6g}" rgba="0.55 0.55 0.55 1"/>')
    x.append(f'    <geom name="collar" type="cylinder" size="0.0625 0.005" pos="0 0 {cfg["collar_z"] + 0.005:.6g}"/>')

    for i, (deg, b, t, m) in enumerate(zip(sled["start_deg"], bottoms, tops, mounts), start=1):
        out = orbit_dir(deg)
        d = v_sub(t, b)
        out_top = orbit_dir(deg + twist)
        # + swivel twists the neck further, at both ends. The top joint turns the platform side
        # relative to the rod, so its axis is reversed.
        swivel_axis = v_unit(v_cross(out, v_unit(d)))
        swivel_axis_top = v_unit(v_cross(v_unit(v_scale(d, -1)), out_top))
        swivel_range = f'range="{-math.radians(rod_end["untwist_deg"]):.6g} 0.005" solreflimit="0.005 1"'
        sled_c = v_add(v_scale(out, pinion_dist), [0, 0, cfg["collar_z"] + 0.012])
        yaw = math.atan2(out[1], out[0])
        quat = [math.cos(yaw / 2), 0, 0, math.sin(yaw / 2)]

        x.append(f'    <body name="sled_{i}">')
        x.append(f'      <joint name="sled_{i}" type="hinge" axis="0 0 1" ref="{math.radians(deg):.6g}"'
                 ' damping="0.05" armature="0.001"/>')
        x.append(f'      <geom name="sled_{i}" class="sled_collide" type="box"'
                 f' size="0.012 {sled["half_width"]:.6g} 0.012" pos="{fmt(sled_c)}" quat="{fmt(quat)}"'
                 f' mass="{sled["mass"]}" rgba="0.2 0.35 0.8 1"/>')
        x.append(f'      <site name="sled_{i}_pivot" pos="{fmt(b)}" size="0.003"/>')
        x.append(f'      <body name="rod_{i}" pos="{fmt(b)}" childclass="rod_end">')
        x.append(f'        <joint name="rod_{i}_swing" type="hinge" axis="{fmt(out)}"/>')
        x.append(f'        <joint name="rod_{i}_swivel" type="hinge" axis="{fmt(swivel_axis)}" {swivel_range}/>')
        x.append(f'        <joint name="rod_{i}_spin" type="hinge" axis="{fmt(v_unit(d))}"/>')
        x.append(f'        <geom name="rod_{i}" type="capsule" fromto="0 0 0 {fmt(d)}"'
                 f' size="{rod["radius"]}" mass="{rod["mass"]}" rgba="0.75 0.75 0.75 1"/>')
        x.append(f'        <site name="rod_{i}_spring" pos="{fmt(v_sub(m, b))}" size="0.002"/>')
        x.append(f'        <body name="rod_{i}_top" pos="{fmt(d)}">')
        x.append(f'          <joint name="rod_{i}_top_swivel" type="hinge" axis="{fmt(swivel_axis_top)}" {swivel_range}/>')
        x.append(f'          <joint name="rod_{i}_top_swing" type="hinge" axis="{fmt(out_top)}"/>')
        x.append('          <geom type="sphere" size="0.003" mass="0.001" rgba="0.1 0.3 0.9 1"/>')
        x.append("        </body>")
        x.append("      </body>")
        x.append("    </body>")

    # The platform floats; only the rods hold it. Its frame is level and centred at the rest pose.
    x.append(f'    <body name="platform" pos="0 0 {z_top:.6g}">')
    x.append('      <freejoint name="platform"/>')
    # Mass and inertia are a platform.radius cylinder, 8 mm thick, as before the shapes were added for looks.
    r, h, m = plat["radius"], 0.008, plat["mass"]
    x.append(f'      <inertial pos="0 0 0" mass="{m}" diaginertia="{m * (3 * r * r + h * h) / 12:.6g}'
             f' {m * (3 * r * r + h * h) / 12:.6g} {m * r * r / 2:.6g}"/>')
    x.append('      <geom name="platform" type="mesh" mesh="platform" density="0" rgba="0.45 0.45 0.5 1"/>')
    # The head, rotated by head.rotation_deg from rod end 1: a thin disk on the platform with the eyes on
    # it and a stripe marking forward, and the head site. The disk and stripe are massless, for looks.
    x.append(f'      <body name="head" quat="{math.cos(facing / 2):.6g} 0 0 {math.sin(facing / 2):.6g}">')
    x.append(f'        <geom name="head_disk" type="cylinder" size="{plat["radius"]} 0.0015" pos="0 0 0.0055"'
             ' density="0" rgba="0.8 0.8 0.85 0.35"/>')
    x.append(f'        <geom name="head_forward" type="box" size="{plat["radius"] / 2:.6g} 0.002 0.0001"'
             f' pos="{plat["radius"] / 2:.6g} 0 0.0071" density="0" rgba="0.92 0.41 0.2 1"/>')
    for side, y in (("left", 0.02), ("right", -0.02)):
        x.append(f'        <geom name="eye_{side}" type="cylinder" size="0.016 0.003" pos="0.03 {y} 0.025"'
                 ' euler="0 1.5708 0" mass="0.001" rgba="1 1 1 1"/>')
    x.append('        <site name="head" pos="0 0 0" size="0.004"/>')
    x.append("      </body>")
    x.append("    </body>")
    x.append("  </worldbody>")

    x.append("  <equality>")
    # relpose: the platform's pose in the top rod end's frame, at rest (both frames are unrotated).
    for i, t in enumerate(tops, start=1):
        rel = v_sub([0, 0, z_top], t)
        x.append(f'    <weld name="rod_{i}_top" body1="rod_{i}_top" body2="platform"'
                 f' relpose="{fmt(rel)} 1 0 0 0" solref="0.002 1"/>')
    x.append("  </equality>")

    # springlength is a range: no force between 0 and the rest length, so the springs only pull.
    x.append("  <tendon>")
    for i in range(3):
        a, b = i + 1, (i + 1) % 3 + 1
        x.append(f'    <spatial name="spring_{a}_{b}" stiffness="{springs["stiffness"]}"'
                 f' springlength="0 {springs["free_length"]}" damping="0.5" width="0.002" rgba="0.8 0.8 0.3 1">')
        x.append(f'      <site site="rod_{a}_spring"/>')
        x.append(f'      <site site="rod_{b}_spring"/>')
        x.append("    </spatial>")
    x.append("  </tendon>")

    # Actuator names must match the ros2_control joint names.
    x.append("  <actuator>")
    for i in range(1, 4):
        x.append(f'    <position name="sled_{i}" joint="sled_{i}" kp="50" dampratio="1" forcerange="-5 5"/>')
    x.append("  </actuator>")

    # The head pose, for mujoco_ros2_control's pose sensor (names: <sensor>_pos, <sensor>_quat).
    x.append("  <sensor>")
    x.append('    <framepos name="head_pos" objtype="site" objname="head"/>')
    x.append('    <framequat name="head_quat" objtype="site" objname="head"/>')
    x.append("  </sensor>")
    x.append("</mujoco>")
    return "\n".join(x) + "\n"


def main():
    if len(sys.argv) != 4 or sys.argv[2] not in ("CW", "CCW"):
        sys.exit(__doc__.splitlines()[2])
    with open(sys.argv[1]) as f:
        cfg = yaml.safe_load(f)
    xml = build(cfg, sys.argv[2])
    with open(sys.argv[3], "w") as f:
        f.write(xml)


if __name__ == "__main__":
    main()
